"""Blob storage for uploaded statements (ADR-0026).

Keys are generated by the application (`users/<user_id>/imports/<import_id>`), never derived
from file names. Stored bytes are always the original, still bank-encrypted file.
"""

import asyncio
import os
import re
import uuid
from pathlib import Path
from typing import Protocol

_KEY = re.compile(r"^[a-z0-9][a-z0-9_\-]*(/[a-z0-9][a-z0-9_\-]*)*$")


class BlobNotFound(Exception):
    pass


class BlobStore(Protocol):
    async def put(self, key: str, data: bytes) -> None: ...
    async def get(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...
    async def exists(self, key: str) -> bool: ...


def import_blob_key(user_id: uuid.UUID, import_id: uuid.UUID) -> str:
    return f"users/{user_id}/imports/{import_id}"


def validate_key(key: str) -> str:
    if len(key) > 200 or not _KEY.match(key):
        raise ValueError("invalid blob key")
    return key


class LocalFsBlobStore:
    """Files under one root directory (a Docker volume shared by api and worker in v1)."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / validate_key(key)).resolve()
        if self.root not in path.parents:
            raise ValueError("invalid blob key")
        return path

    async def put(self, key: str, data: bytes) -> None:
        await asyncio.to_thread(self._put, self._path(key), data)

    @staticmethod
    def _put(path: Path, data: bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        # Owner-only permissions where the OS supports them.
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0), 0o600)
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            tmp.replace(path)  # atomic: readers never see a half-written file
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await asyncio.to_thread(path.read_bytes)
        except FileNotFoundError as exc:
            raise BlobNotFound(key) from exc

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._path(key).unlink, missing_ok=True)

    async def exists(self, key: str) -> bool:
        return await asyncio.to_thread(self._path(key).is_file)
