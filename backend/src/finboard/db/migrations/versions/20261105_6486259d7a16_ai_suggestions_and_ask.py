# Account aliases ("Account A", …) in a fixed order (created_at, id); finboard.ai.aliases
# builds the same list for prompts. Amounts are signed per metric (ADR-0017): positive adds
# to the type's metric, transfers count 0.
AI_TXN = """
CREATE VIEW ai_txn AS
SELECT t.date,
       to_char(t.date, 'YYYY-MM') AS month,
       CASE WHEN a.rank <= 26 THEN 'Account ' || chr(64 + a.rank::int)
            ELSE 'Account ' || a.rank END AS account,
       a.type AS account_type,
       c.name AS category,
       p.name AS parent_category,
       t.type,
       t.direction,
       (CASE
          WHEN t.type = 'income' AND t.direction = 'credit' THEN t.amount
          WHEN t.type = 'income' THEN -t.amount
          WHEN t.type IN ('expense', 'investment') AND t.direction = 'debit' THEN t.amount
          WHEN t.type IN ('expense', 'investment') THEN -t.amount
          ELSE 0
        END)::numeric(14, 2) AS signed_amount,
       COALESCE(t.payee_label, t.description_norm) AS merchant
FROM txn t
JOIN (SELECT user_id, id, type,
             dense_rank() OVER (PARTITION BY user_id ORDER BY created_at, id) AS rank
      FROM account) a ON a.user_id = t.user_id AND a.id = t.account_id
JOIN category c ON c.user_id = t.user_id AND c.id = t.category_id
LEFT JOIN category p ON p.user_id = c.user_id AND p.id = c.parent_id
"""

# The limit in force per month (domain/budgets.py semantics), up to 12 months ahead.
AI_BUDGET = """
CREATE VIEW ai_budget AS
SELECT to_char(m.month, 'YYYY-MM') AS month, c.name AS category, b.monthly_limit
FROM category c
CROSS JOIN LATERAL generate_series(
    (SELECT min(b0.effective_from) FROM budget b0
     WHERE b0.user_id = c.user_id AND b0.category_id = c.id),
    date_trunc('month', now()) + interval '12 months',
    interval '1 month') AS m(month)
CROSS JOIN LATERAL (
    SELECT b1.monthly_limit FROM budget b1
    WHERE b1.user_id = c.user_id AND b1.category_id = c.id AND b1.effective_from <= m.month
    ORDER BY b1.effective_from DESC LIMIT 1) b
WHERE b.monthly_limit IS NOT NULL
"""

